#!/usr/bin/env -S uv run
# /// script
# requires-python = ">=3.11"
# dependencies = ["resvg-py>=0.2", "pillow>=10.1"]
# ///
"""Build the committed icon assets that install.zsh copies into the app bundle.

Usage: assets/icon/render.py [build]

From layers/{bg,fg,fg2}.svg (the source of truth) and MenuBar*.svg it writes:
- AppIcon.svg: the flattened composite (bg, fg, fg2 clipped to the tile, with shadow and sheen);
- AppIcon.icns: the pre-macOS 26 fallback, rendered from AppIcon.svg via iconutil;
- AppIcon.icon/Assets/{fg,fg2}.svg and Assets.car: the Liquid Glass icon, compiled by actool (needs Xcode 26+);
- MenuBar*.png: 18pt template images (@1x/@2x) for the status item.
"""
import io
import shutil
import subprocess
import tempfile
from pathlib import Path

import resvg_py
from PIL import Image

ICON = Path(__file__).parent
LAYERS = ICON / "layers"
BUNDLE = ICON / "AppIcon.icon"

# Tile geometry, shadow and sheen follow the pre-#64 AppIcon.svg.
FLAT = """<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by render.py from layers/{{bg,fg,fg2}}.svg: edit those, then re-run it. -->
  <defs>
    <clipPath id="tile"><rect x="100" y="100" width="824" height="824" rx="185"/></clipPath>
    <linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="0.22"/>
      <stop offset="0.5" stop-color="#fff" stop-opacity="0"/>
    </linearGradient>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="10" stdDeviation="12" flood-color="#000" flood-opacity="0.28"/>
    </filter>
    <filter id="lift" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="10" stdDeviation="14" flood-color="#04424F" flood-opacity="0.30"/>
    </filter>
  </defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="#0B6E86" filter="url(#shadow)"/>
  <g clip-path="url(#tile)">
    {bg}
    <g filter="url(#lift)">{fg}{fg2}</g>
  </g>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#sheen)"/>
</svg>
"""


def inner(name: str) -> str:
    """A layer's content without its outer <svg> element."""
    s = (LAYERS / f"{name}.svg").read_text()
    return s[s.index(">") + 1 : s.rindex("</svg>")]


def render(svg: Path, size: int) -> Image.Image:
    png = resvg_py.svg_to_bytes(svg_path=str(svg), width=size, height=size)
    return Image.open(io.BytesIO(bytes(png))).convert("RGBA")


def build() -> None:
    (ICON / "AppIcon.svg").write_text(FLAT.format(bg=inner("bg"), fg=inner("fg"), fg2=inner("fg2")))
    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / "AppIcon.iconset"
        iconset.mkdir()
        for pt in (16, 32, 128, 256, 512):
            render(ICON / "AppIcon.svg", pt).save(iconset / f"icon_{pt}x{pt}.png")
            render(ICON / "AppIcon.svg", pt * 2).save(iconset / f"icon_{pt}x{pt}@2x.png")
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(ICON / "AppIcon.icns")], check=True)
    # The .icon's background is its icon.json "fill" gradient (bg.svg's stops); only the glyph layers are images.
    for name in ("fg", "fg2"):
        shutil.copy(LAYERS / f"{name}.svg", BUNDLE / "Assets" / f"{name}.svg")
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            ["xcrun", "actool", str(BUNDLE), "--compile", tmp, "--platform", "macosx",
             "--minimum-deployment-target", "14.0", "--app-icon", "AppIcon",
             "--output-partial-info-plist", f"{tmp}/partial.plist"],
            check=True, stdout=subprocess.DEVNULL,
        )
        shutil.copy(Path(tmp) / "Assets.car", ICON / "Assets.car")  # raises if actool reported an error
    for name in ("MenuBar", "MenuBarAttention"):
        render(ICON / f"{name}.svg", 18).save(ICON / f"{name}.png")
        render(ICON / f"{name}.svg", 36).save(ICON / f"{name}@2x.png")
    print(f"built AppIcon.svg, AppIcon.icns, Assets.car and MenuBar PNGs in {ICON}")


if __name__ == "__main__":
    build()
